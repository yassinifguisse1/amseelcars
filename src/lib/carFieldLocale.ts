function translatePhrase(value: string, locale: Exclude<AppLocale, 'fr'>): string {
  let out = value.trim()
  // Normalize common lowercase FR tokens before phrase map
  out = out.replace(/^diesel$/i, 'Diesel').replace(/^manuelle$/i, 'Manuelle').replace(/^essence$/i, 'Essence')

  for (const [from, to] of PHRASES[locale]) {
    if (out.includes(from)) out = out.split(from).join(to)
  }
  // Lowercase French fuel word inside engine strings when still present
  if (locale === 'en') out = out.replace(/\bessence\b/gi, 'petrol')
  if (locale === 'es') out = out.replace(/\bessence\b/gi, 'gasolina').replace(/\bdiesel\b/gi, 'diésel')
  if (locale === 'de') out = out.replace(/\bessence\b/gi, 'Benzin')
  if (locale === 'pl') out = out.replace(/\bessence\b/gi, 'benzyna')
  return out.replace(/\s+/g, ' ').trim()
}

export function localizeCarFields(car: Car, locale: AppLocale): Car {
  if (locale === 'fr') return car

  const names = FEATURE_NAMES[locale]
  return {
    ...car,
    fuelType: translatePhrase(car.fuelType, locale),
    transmission: translatePhrase(car.transmission, locale),
    features: car.features.map((f) => ({
      ...f,
      name: names[f.name] ?? translatePhrase(f.name, locale),
      value: translatePhrase(f.value, locale),
    })),
    specs: {
      engine: translatePhrase(car.specs.engine, locale),
      horsepower: translatePhrase(car.specs.horsepower, locale),
      acceleration: translatePhrase(car.specs.acceleration, locale),
      topSpeed: translatePhrase(car.specs.topSpeed, locale),
      fuelEfficiency: translatePhrase(car.specs.fuelEfficiency, locale),
      drivetrain: translatePhrase(car.specs.drivetrain, locale),
    },
  }
}
